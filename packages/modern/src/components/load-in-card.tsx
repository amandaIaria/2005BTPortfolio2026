interface RevealingTentacleProps {
  maskId: string;
  hovered: boolean;
  className?: string;
}

const reveal = {
  hidden: { pathLength: 0, opacity: 0 },
  visible: { pathLength: 1, opacity: 1 },
};

function RevealingTentacle({
  maskId,
  hovered,
  className,
}: RevealingTentacleProps) {
  return (
    <svg
      className={cn(
        'absolute inset-0 w-full h-full pointer-events-none overflow-visible',
        className,
      )}
      viewBox={TENTACLE_VIEWBOX}
      style={{
        top: '8px',
        ...boxScale,
      }}
    >
      <defs>
        <mask
          id={maskId}
          maskUnits="userSpaceOnUse"
          x="0"
          y="0"
          width="423"
          height="513"
        >
          <motion.path
            d={REVEAL_PATH_D}
            fill="none"
            stroke="white"
            strokeWidth={220}
            strokeLinecap="round"
            strokeLinejoin="round"
            variants={reveal}
            initial="visible"
            animate={hovered ? 'visible' : 'hidden'}
            transition={{
              pathLength: { duration: 1, ease: 'easeInOut' },
              opacity: hovered ? { duration: 0 } : { duration: 0, delay: 1 },
            }}
          />
        </mask>
      </defs>
      <g mask={`url(#${maskId})`}>
        <TentacleGraphic />
      </g>
    </svg>
  );
}

export default function LoadInCard({ children, className }: LoadInCardProps) {
  const [groupHovered, setGroupHovered] = useState(false);
  const maskId = useId();
  const cardRef = useRef<HTMLDivElement>(null);
  const { startTransition } = usePageTransition();

  function handleClick(e: MouseEvent<HTMLDivElement>) {
    const anchor = (e.target as HTMLElement).closest('a[href]');
    if (!anchor) return;
    e.preventDefault();
    setGroupHovered(false);
    const bubble = cardRef.current?.parentElement;
    const backgroundColor = bubble
      ? getComputedStyle(bubble).backgroundColor
      : 'var(--surface, #000)';
    startTransition({
      rect: anchor.getBoundingClientRect(),
      href: anchor.getAttribute('href') ?? '/',
      backgroundColor,
    });
  }

  return (
    <motion.div
      ref={cardRef}
      className={`relative w-full h-full ${className}`}
      onClick={handleClick}
      onHoverStart={() => setGroupHovered(true)}
      onHoverEnd={() => setGroupHovered(false)}
    >
      {children}
      <RevealingTentacle
        maskId={maskId}
        hovered={groupHovered}
        className="text-accent"
      />
    </motion.div>
  );
}
